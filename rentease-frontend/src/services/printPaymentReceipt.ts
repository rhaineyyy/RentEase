import type { RentalPayment } from './billing';

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, character => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#039;',
  }[character] || character));
}

function peso(value: string | number): string {
  return new Intl.NumberFormat('en-PH', {
    style: 'currency',
    currency: 'PHP',
    minimumFractionDigits: 2,
  }).format(Number(value || 0));
}

export function printPaymentReceipt(payment: RentalPayment, billingPeriod?: string): void {
  const printWindow = window.open('', '_blank', 'noopener,noreferrer');
  if (!printWindow) {
    throw new Error('Allow pop-ups to generate the payment receipt PDF.');
  }

  const receiptId = escapeHtml(String(payment.payment_id));
  const tenant = escapeHtml(payment.tenant_name || 'Tenant');
  const property = escapeHtml(payment.property_name || 'Rental Property');
  const unit = escapeHtml(`Unit ${payment.unit_number}`);
  const method = escapeHtml(payment.payment_method.replaceAll('_', ' ').toUpperCase());
  const reference = escapeHtml(payment.reference_number || 'Cash payment');
  const date = escapeHtml(String(payment.payment_date).slice(0, 10));
  const period = escapeHtml(billingPeriod || 'Billing statement');
  const status = escapeHtml(payment.status.replaceAll('_', ' ').toUpperCase());

  printWindow.document.write(`<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>RentEase Payment Receipt #${receiptId}</title>
  <style>
    @page { size: A5; margin: 12mm; }
    * { box-sizing: border-box; }
    body { background: #f5f8fc; color: #172b4d; font: 13px/1.5 Arial, sans-serif; margin: 0; }
    .receipt { background: #fff; border: 1px solid #d5e0ef; border-radius: 12px; margin: 0 auto; max-width: 470px; overflow: hidden; }
    header { background: linear-gradient(120deg, #123d8f, #176cc9 65%, #20b5bb); color: #fff; padding: 22px 24px; }
    .brand { font-size: 24px; font-weight: 800; letter-spacing: .5px; }
    .subtitle { font-size: 11px; opacity: .85; }
    .title { font-size: 19px; font-weight: 800; letter-spacing: .8px; margin-top: 21px; text-transform: uppercase; }
    main { padding: 23px 24px; }
    .paid-label { color: #657895; font-size: 10px; letter-spacing: 1.2px; text-transform: uppercase; }
    .amount { color: #1452a0; font-size: 31px; font-weight: 800; margin: 3px 0 18px; }
    .status { background: #e8f7ef; border: 1px solid #bfe7ce; border-radius: 20px; color: #187344; display: inline-block; font-size: 10px; font-weight: 800; padding: 4px 10px; }
    .details { border-top: 1px dashed #cbd8e8; margin-top: 18px; padding-top: 8px; }
    .row { border-bottom: 1px solid #edf1f6; display: flex; gap: 16px; justify-content: space-between; padding: 9px 0; }
    .label { color: #657895; font-size: 11px; }
    .value { font-size: 12px; font-weight: 700; text-align: right; }
    .note { background: #f2f7fd; border-radius: 7px; color: #657895; font-size: 10px; margin-top: 20px; padding: 10px; }
    footer { border-top: 1px solid #d5e0ef; color: #657895; font-size: 10px; padding: 13px 24px 18px; text-align: center; }
    @media print { body { background: #fff; } .receipt { border: 0; } }
  </style>
</head>
<body>
  <section class="receipt">
    <header><div class="brand">RentEase</div><div class="subtitle">Digital Rental Management Platform</div><div class="title">Payment Receipt</div></header>
    <main>
      <div class="paid-label">Payment amount</div>
      <div class="amount">${peso(payment.amount)}</div>
      <span class="status">${status}</span>
      <div class="details">
        <div class="row"><span class="label">Receipt No.</span><span class="value">#${receiptId}</span></div>
        <div class="row"><span class="label">Tenant</span><span class="value">${tenant}</span></div>
        <div class="row"><span class="label">Property / Unit</span><span class="value">${property}<br>${unit}</span></div>
        <div class="row"><span class="label">Billing period</span><span class="value">${period}</span></div>
        <div class="row"><span class="label">Payment date</span><span class="value">${date}</span></div>
        <div class="row"><span class="label">Payment method</span><span class="value">${method}</span></div>
        <div class="row"><span class="label">Reference number</span><span class="value">${reference}</span></div>
      </div>
      <div class="note">This receipt is a generated copy of the payment record in RentEase. A payment remains subject to owner verification unless its status is marked VERIFIED.</div>
    </main>
    <footer>Generated by RentEase · Keep this receipt for your records.</footer>
  </section>
</body>
</html>`);
  printWindow.document.close();
  printWindow.focus();
  printWindow.onload = () => printWindow.print();
}
